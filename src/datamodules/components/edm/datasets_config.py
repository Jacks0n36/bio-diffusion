from typing import Any, Dict

from torchtyping import patch_typeguard
from typeguard import typechecked

patch_typeguard()  # use before @typechecked


@typechecked
def get_dataset_info(dataset_name: str, remove_h: bool) -> Dict[str, Any]:
    if dataset_name == "QM9":
        if not remove_h:
            return QM9_WITH_H
        else:
            return QM9_WITHOUT_H
    elif dataset_name == "GEOM":
        if not remove_h:
            return GEOM_WITH_H
        else:
            raise Exception(f"Missing config for {dataset_name} without hydrogens")
    elif dataset_name == "QM9_second_half":
        if not remove_h:
            return QM9_SECOND_HALF
        else:
            raise Exception(f"Missing config for {dataset_name} without hydrogens")
    elif dataset_name == "MolPILE":
        if not remove_h:
            return MolPILE_WITH_H
        else:
            return MolPILE_NO_H
    else:
        raise Exception("Wrong dataset %s" % dataset_name)


